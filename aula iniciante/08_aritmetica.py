'''
matematica 
somos ensinados a usar para contas o sinal de + para somas, o sinal de - para subtracao,
sinal de * multiplicacao, o sinal de / divisao e tambem // para divisao inteira
EXEMPLOS:
'''
adicao = 10 + 10
print('adicao:', adicao)

subtracao = 10 - -5
print('subtracao:', subtracao)

multiplicacao = 10 * 10
print('multiplicacao:', multiplicacao)

divisao = 10 / 2.2
print('divisao:', divisao)

divisao_inteira = 10 // 2.2
print('divisao inteira:', divisao_inteira)

exponenciacao = 2 ** 10
print('exponenciacao:', exponenciacao)

modulo = 55 % 2 
print('modulo:', modulo)

