'''
Operação ternaria (condicional de uma linha)
        EXEMPLO BASICO
<valor> if <condicao> else <outro valor>
'''
condicao = 10 == 10 # nesse exemplo declarei uma condicao que é true 
variavel = 'Valor' if condicao else 'Outro valor' # aqui temos um exemplo de condição ternária, recebendo o true de condicao
print(variavel) 