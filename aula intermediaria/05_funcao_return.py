'''
Retorno de valores das funções (return)
'''

def soma(x,y):
    return x + y # a funcao return serve para retornar o valor da funcao para poder ser inserido em uma variavel ou qualquer outra coisa, se fosse com o metodo print nao daria certo

soma1 = soma(3,5) # esta recebendo o resultado da função soma e guardando na variavel o valor
soma2 = soma(2,8) # esta recebendo o resultado da função soma e guardando na variavel o valor

print(soma1 + soma2) # esta somando os valores que foram armazenados

